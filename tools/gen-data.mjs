#!/usr/bin/env node
/**
 * Generates the static game data modules in src/data/ from the project's sources of truth:
 *
 *   game_resources/card_text.json   card titles and texts, English and Chinese (authoritative: our Chinese
 *                                   card images are drawn with these titles)
 *   docs/notes/cards_meta.json      engine card metadata (ops, side, era, starred, scoring, war card),
 *                                   extracted from DeepStruggle's engine/src/card_data.cpp
 *   docs/notes/countries.json       the 84 countries (engine table + rules/map.json + board positions)
 *   src/data/ds/cards.json          DeepStruggle rules/cards.json, cross-checked field by field
 *   src/data/ds/map.json            DeepStruggle rules/map.json, cross-checked field by field
 *
 * Outputs: src/data/cards.ts, src/data/countries.ts (both marked GENERATED; do not edit them by hand).
 *
 * Usage:
 *   node tools/gen-data.mjs          write the outputs
 *   node tools/gen-data.mjs --check  exit 1 if an output is stale (tests/i18n/data.test.ts does the same)
 *
 * Chinese country names: DeepStruggle's zh-CN names, reviewed. The overrides below make the
 * multi-country boxes follow one pattern ("…国家", as our card #52 writes 东南非洲国家) and shorten
 * Benelux to its usual Chinese name. See docs/glossary.md.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const readJson = rel => JSON.parse(readFileSync(join(ROOT, rel), "utf8"));

