/** Engine Region enum (engine/include/ts/types.hpp): note Asia is 1 and the Middle East 2. */
const REGIONS = [
  { id: 0, key: "EUROPE", en: "Europe", zh: "欧洲", scoringCard: 2 },
  { id: 1, key: "ASIA", en: "Asia", zh: "亚洲", scoringCard: 1 },
  { id: 2, key: "MIDDLE_EAST", en: "Middle East", zh: "中东", scoringCard: 3 },
  { id: 3, key: "AFRICA", en: "Africa", zh: "非洲", scoringCard: 79 },
  { id: 4, key: "CENTRAL_AMERICA", en: "Central America", zh: "中美洲", scoringCard: 37 },
  { id: 5, key: "SOUTH_AMERICA", en: "South America", zh: "南美洲", scoringCard: 81 },
];
const SUBREGIONS = [
  { key: "WESTERN_EUROPE", en: "Western Europe", zh: "西欧", region: 0, scoringCard: null },
  { key: "EASTERN_EUROPE", en: "Eastern Europe", zh: "东欧", region: 0, scoringCard: null },
  { key: "SOUTHEAST_ASIA", en: "Southeast Asia", zh: "东南亚", region: 1, scoringCard: 38 },
];
const SIDE = { US: "US", USSR: "USSR", neutral: "NEUTRAL" };
const DS_SIDE = { us: "US", ussr: "USSR", neutral: "NEUTRAL" };
const DS_AGE = { "early war": "early", "middle war": "mid", "late war": "late" };

function fail(msg) {
  throw new Error(`gen-data: ${msg}`);
}
function check(cond, msg) {
  if (!cond) fail(msg);
}

// The generated modules carry DeepStruggle-derived data (engine metadata, rules/*.json, its English card
// text and Chinese country names), so they keep its MIT header.
const HEADER = source =>
  "// Ported from DeepStruggle (https://github.com/mihaild/DeepStruggle, commit 5b95e91), MIT License,\n" +
  "// Copyright (c) 2026 Mikhail Dektyarev. See THIRD_PARTY_LICENSES.md.\n" +
  `// GENERATED by tools/gen-data.mjs from ${source}.\n// Do not edit by hand: change the sources or the generator and run \`node tools/gen-data.mjs\`.\n`;

const lit = v => JSON.stringify(v);
const bi = (en, zh) => `{ en: ${lit(en)}, zh: ${lit(zh)} }`;

export function buildCards() {
  const text = readJson("game_resources/card_text.json");
  const meta = readJson("docs/notes/cards_meta.json");
  const ds = readJson("src/data/ds/cards.json");
  const textById = new Map(text.cards.map(c => [c.id, c]));
  const dsById = new Map(ds.map(c => [c.id, c]));
  check(meta.length === 110, `cards_meta.json has ${meta.length} cards, expected 110`);

  const rows = [];
  for (const m of meta) {
    const t = textById.get(m.id);
    const d = dsById.get(m.id);
    check(t, `card_text.json lacks card ${m.id}`);
    check(d, `ds/cards.json lacks card ${m.id}`);
    // The engine metadata must agree with DeepStruggle's rules/cards.json and with our English titles.
    check(d.ops === m.ops, `card ${m.id}: ops ${m.ops} vs ds ${d.ops}`);
    check(DS_SIDE[d.side] === SIDE[m.side], `card ${m.id}: side ${m.side} vs ds ${d.side}`);
    check(DS_AGE[d.age] === m.era, `card ${m.id}: era ${m.era} vs ds ${d.age}`);
    check(d.one_time === m.starred, `card ${m.id}: starred ${m.starred} vs ds ${d.one_time}`);
    check(d.name === t.title_en, `card ${m.id}: our English title ${lit(t.title_en)} is not the engine's ${lit(d.name)}`);
    for (const k of ["title_en", "title_zh", "text_en", "text_zh"]) {
      check(typeof t[k] === "string" && t[k].trim() === t[k] && t[k].length > 0, `card ${m.id}: bad ${k}`);
    }
    rows.push(
      `  {\n` +
        `    id: ${m.id}, ops: ${m.ops}, side: ${lit(SIDE[m.side])}, era: ${lit(m.era)},\n` +
        `    starred: ${m.starred}, scoring: ${m.scoring}, war: ${m.war_card}, optional: ${m.optional},\n` +
        `    title: ${bi(t.title_en, t.title_zh)},\n` +
        `    text: {\n      en: ${lit(t.text_en)},\n      zh: ${lit(t.text_zh)},\n    },\n` +
        `  },`,
    );
  }
  check(text.cards.length === 110, `card_text.json has ${text.cards.length} cards`);

  return `${HEADER("game_resources/card_text.json, docs/notes/cards_meta.json and src/data/ds/cards.json")}
/**
 * The 110 cards of the Deluxe Edition (optional cards #104-110 included), by engine card id.
 * Titles and texts are ours (game_resources/card_text.json): the Chinese card images are drawn with
 * these titles, so they win over DeepStruggle's catalogs. Metadata is the engine's (card_data.cpp).
 *
 * Text markup: \`text.zh\` uses "\\n" for line breaks and "*…*" for italics (card references and the
 * italic rule notes printed on the cards); \`text.en\` is one plain paragraph. Use
 * \`cardTextLines\` (src/data/index.ts) to render either.
 */

export type CardSide = "US" | "USSR" | "NEUTRAL";
export type CardEra = "early" | "mid" | "late";

export interface CardInfo {
  /** Engine card id, 1..110 (6 = The China Card). */
  readonly id: number;
  /** Printed Operations value (0 for scoring cards; The China Card is 4). */
  readonly ops: number;
  /** Whose Event it is. */
  readonly side: CardSide;
  readonly era: CardEra;
  /** Removed from play after its Event (the asterisk); Southeast Asia Scoring: removed after scoring. */
  readonly starred: boolean;
  readonly scoring: boolean;
  /** A war card (Flower Power counts these): 11, 13, 24, 36, 102. */
  readonly war: boolean;
  /** Optional card #104-110 (always in the deck under our rules). */
  readonly optional: boolean;
  readonly title: { readonly en: string; readonly zh: string };
  readonly text: { readonly en: string; readonly zh: string };
}

/** Index 0 is unused; \`CARDS[id - 1].id === id\`. Prefer \`cardInfo(id)\`. */
export const CARDS: readonly CardInfo[] = [
${rows.join("\n")}
];
`;
}

export function buildCountries() {
  const countries = readJson("docs/notes/countries.json");
  const map = readJson("src/data/ds/map.json");
  check(countries.length === 84, `countries.json has ${countries.length} countries`);
  const byName = new Map(countries.map(c => [c.name, c]));
  const dsByName = new Map(map.countries.map(c => [c.name, c]));
  const subKey = Object.fromEntries(SUBREGIONS.map(s => [s.en, s.key]));

  const rows = [];
  countries.forEach((c, i) => {
    check(c.id === i, `countries.json is not ordered by id at ${i}`);
    const d = dsByName.get(c.name);
    check(d, `ds/map.json lacks ${c.name}`);
    check(d.id === c.id && d.stability === c.stability && d.battleground === c.battleground, `country ${c.id} differs from ds/map.json`);
    check(REGIONS[c.region_id].en === c.region && d.region === c.region, `country ${c.id}: region mismatch`);
    check(REGIONS[c.region_id].zh === c.region_zh, `country ${c.id}: region zh ${c.region_zh}`);
    const dsNeighbours = d.neighbours.map(n => byName.get(n)?.id).sort((a, b) => a - b);
    check(lit(dsNeighbours) === lit([...c.neighbours].sort((a, b) => a - b)), `country ${c.id}: neighbours differ from ds/map.json`);
    check(lit(d.subregions ?? []) === lit(c.subregions), `country ${c.id}: subregions differ`);
    // rules/map.json says "USA"; the engine and its display state say "US".
    const sp = c.superpower_adjacent === "USA" ? "US" : c.superpower_adjacent;
    check(sp === null || sp === "US" || sp === "USSR", `country ${c.id}: superpower ${c.superpower_adjacent}`);
    check((d.superpower_adjacent ?? null) === c.superpower_adjacent, `country ${c.id}: superpower differs from ds/map.json`);
    const zh = ZH_NAME_OVERRIDES[c.id] ?? c.name_zh;
    check(zh && zh.length > 0, `country ${c.id}: no Chinese name`);
    const shortEn = EN_SHORT_NAMES[c.id] ?? c.short_name_en ?? c.name;
    const shortZh = ZH_SHORT_NAMES[c.id] ?? zh;
    const subs = c.subregions.map(s => {
      check(subKey[s], `country ${c.id}: unknown subregion ${s}`);
      return lit(subKey[s]);
    });
    const ref = c.ref_box;
    check(Array.isArray(ref) && ref.length === 4 && Array.isArray(c.ds_pos), `country ${c.id}: layout`);
    rows.push(
      `  {\n` +
        `    id: ${c.id}, engineName: ${lit(c.name)},\n` +
        `    name: ${bi(c.name, zh)}, short: ${bi(shortEn, shortZh)},\n` +
        `    region: ${c.region_id}, subregions: [${subs.join(", ")}], stability: ${c.stability}, battleground: ${c.battleground},\n` +
        `    superpowerAdjacent: ${lit(sp)}, neighbours: [${c.neighbours.join(", ")}],\n` +
        `    layout: { ds: [${c.ds_pos.join(", ")}], board: [${ref.join(", ")}] },\n` +
        `  },`,
    );
  });
  // Adjacency must be symmetric.
  for (const c of countries) for (const n of c.neighbours) {
    check(countries[n].neighbours.includes(c.id), `adjacency ${c.id}-${n} is not symmetric`);
  }

  const regionRows = REGIONS.map(r =>
    `  { id: ${r.id}, key: ${lit(r.key)}, name: ${bi(r.en, r.zh)}, scoringCard: ${r.scoringCard}, ` +
      `countries: [${countries.filter(c => c.region_id === r.id).map(c => c.id).join(", ")}] },`);
  const subRows = SUBREGIONS.map(s =>
    `  { key: ${lit(s.key)}, name: ${bi(s.en, s.zh)}, region: ${s.region}, scoringCard: ${lit(s.scoringCard)}, ` +
      `countries: [${countries.filter(c => c.subregions.includes(s.en)).map(c => c.id).join(", ")}] },`);

  return `${HEADER("docs/notes/countries.json and src/data/ds/map.json")}
/**
 * The 84 countries of the map by engine country id (0..83), the six regions by the engine's Region
 * enum (EUROPE 0, ASIA 1, MIDDLE_EAST 2, AFRICA 3, CENTRAL_AMERICA 4, SOUTH_AMERICA 5 -- not board
 * order) and the three subregions. The engine's display state keys \`state.countries\` by
 * \`engineName\`; always join on \`id\`.
 */

export type RegionId = 0 | 1 | 2 | 3 | 4 | 5;
export type RegionKey = "EUROPE" | "ASIA" | "MIDDLE_EAST" | "AFRICA" | "CENTRAL_AMERICA" | "SOUTH_AMERICA";
export type SubregionKey = "WESTERN_EUROPE" | "EASTERN_EUROPE" | "SOUTHEAST_ASIA";

export interface CountryInfo {
  /** Engine country id 0..83 (also the action-space node id). */
  readonly id: number;
  /** The engine's name: the key of the display state's \`countries\` object. */
  readonly engineName: string;
  readonly name: { readonly en: string; readonly zh: string };
  /** Short label for tight map boxes (ui-spec §4.3): DeepStruggle's English abbreviations plus the map-only ones (EN_SHORT_NAMES, ZH_SHORT_NAMES in tools/gen-data.mjs); else the full name. */
  readonly short: { readonly en: string; readonly zh: string };
  readonly region: RegionId;
  /** Austria and Finland are in both Western and Eastern Europe. */
  readonly subregions: readonly SubregionKey[];
  readonly stability: number;
  readonly battleground: boolean;
  /** Adjacent to a superpower ("US" normalised from rules/map.json's "USA"). */
  readonly superpowerAdjacent: "US" | "USSR" | null;
  /** Adjacent country ids (symmetric). */
  readonly neighbours: readonly number[];
  readonly layout: {
    /** DeepStruggle map_view.ts box centre, viewBox 0 0 1000 650. */
    readonly ds: readonly [number, number];
    /** Country box [left, top, right, bottom] on game_resources/TS_map.jpg (2448x1584), ±2 px. */
    readonly board: readonly [number, number, number, number];
  };
}

export interface RegionInfo {
  readonly id: RegionId;
  readonly key: RegionKey;
  readonly name: { readonly en: string; readonly zh: string };
  readonly scoringCard: number;
  readonly countries: readonly number[];
}

export interface SubregionInfo {
  readonly key: SubregionKey;
  readonly name: { readonly en: string; readonly zh: string };
  readonly region: RegionId;
  /** Southeast Asia Scoring (#38); none for the two halves of Europe. */
  readonly scoringCard: number | null;
  readonly countries: readonly number[];
}

/** \`COUNTRIES[id].id === id\`. */
export const COUNTRIES: readonly CountryInfo[] = [
${rows.join("\n")}
];

/** \`REGIONS[id].id === id\` (engine Region enum order). */
export const REGIONS: readonly RegionInfo[] = [
${regionRows.join("\n")}
];

export const SUBREGIONS: readonly SubregionInfo[] = [
${subRows.join("\n")}
];
`;
}

export const OUTPUTS = {
  "src/data/cards.ts": buildCards,
  "src/data/countries.ts": buildCountries,
};

function main() {
  const checkOnly = process.argv.includes("--check");
  let stale = 0;
  for (const [rel, build] of Object.entries(OUTPUTS)) {
    const out = build();
    const path = join(ROOT, rel);
    let current = null;
    try { current = readFileSync(path, "utf8"); } catch { /* missing */ }
    if (current === out) { console.log(`${rel}: up to date`); continue; }
    if (checkOnly) { console.error(`${rel}: STALE (run node tools/gen-data.mjs)`); stale++; continue; }
    writeFileSync(path, out);
    console.log(`${rel}: written`);
  }
  if (stale) process.exit(1);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
