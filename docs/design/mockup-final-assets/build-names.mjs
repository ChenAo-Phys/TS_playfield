// Extracts country and card names (our glossary, src/data) for the final mockup.
//   node docs/design/mockup-final-assets/build-names.mjs   → names.js
// Design artefact only; the production UI imports src/data directly.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../../..");
const ctry = readFileSync(resolve(root, "src/data/countries.ts"), "utf8");
const cards = readFileSync(resolve(root, "src/data/cards.ts"), "utf8");
const countries = {};
for (const m of ctry.matchAll(/id: (\d+), engineName: "[^"]*",\s*name: \{ en: "([^"]*)", zh: "([^"]*)" \}, short: \{ en: "([^"]*)", zh: "([^"]*)" \}/g)) {
  countries[m[1]] = { en: m[2], zh: m[3], enShort: m[4], zhShort: m[5] };
}
const cardNames = {};
for (const m of cards.matchAll(/id: (\d+),[\s\S]*?title: \{ en: "((?:[^"\\]|\\.)*)", zh: "((?:[^"\\]|\\.)*)" \}/g)) {
  cardNames[m[1]] = { en: JSON.parse(`"${m[2]}"`), zh: JSON.parse(`"${m[3]}"`) };
}
const n = Object.keys(countries).length, c = Object.keys(cardNames).length;
if (n !== 84 || c < 110) throw new Error(`parsed ${n} countries, ${c} cards`);
writeFileSync(resolve(here, "names.js"), "// Generated by build-names.mjs from src/data. Do not edit.\nwindow.TS_NAMES = " + JSON.stringify({ countries, cards: cardNames }) + ";\n");
console.log({ countries: n, cards: c });
