// Generates layout.js for the modern-board mockup from docs/notes/{countries,cards_meta,board_ref_positions}.json.
// Run from the repo root:  node docs/design/mockup-modern-board-assets/build-layout.mjs
// World coordinates = the 2448x1584 reference board (TS_map.jpg), unchanged positions; only the
// viewBox is cropped to the country area because the tracks move into the HUD.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const countries = JSON.parse(readFileSync(join(root, "docs/notes/countries.json"), "utf8"));
const cards = JSON.parse(readFileSync(join(root, "docs/notes/cards_meta.json"), "utf8"));
const ref = JSON.parse(readFileSync(join(root, "docs/notes/board_ref_positions.json"), "utf8"));

// Glossary (map-i18n-assets §3.6): one form for the multi-country boxes.
const ZH_FIX = { 49: "西非国家", 50: "撒哈拉国家", 61: "东南非洲国家", 27: "海湾国家" };

const out = {
  world: { x: 30, y: 72, w: 2342, h: 1374 },
  tile: { w: 96, h: 64, strip: 26 },
  countries: countries.map((c) => ({
    id: c.id,
    en: c.name,
    short: c.short_name_en ?? null,
    zh: ZH_FIX[c.id] ?? c.name_zh,
    r: c.region_id,
    we: c.subregions.includes("Western Europe"),
    ee: c.subregions.includes("Eastern Europe"),
    sea: c.subregions.includes("Southeast Asia"),
    s: c.stability,
    bg: c.battleground,
    sp: c.superpower_adjacent === "USA" ? "US" : c.superpower_adjacent, // normalise (critique §3.10)
    n: c.neighbours,
    x: c.ref_x,
    y: c.ref_y,
  })),
  superpowers: {
    US: { x: ref.superpowers.USA.node_xy[0], y: ref.superpowers.USA.node_xy[1] },
    USSR: { x: ref.superpowers.USSR.node_xy[0], y: ref.superpowers.USSR.node_xy[1] },
  },
  scoringBoxes: ref.scoring_boxes,
  cards: Object.fromEntries(
    cards.map((c) => [c.id, { ops: c.ops, side: c.side, era: c.era, star: c.starred, sc: c.scoring, war: c.war_card, opt: c.optional, en: c.title_en, zh: c.title_zh }]),
  ),
};
const regionIds = new Map(countries.map((c) => [c.id, c.region_id]));
const edges = [];
for (const c of countries) for (const n of c.neighbours) if (n > c.id) edges.push([c.id, n, regionIds.get(n) !== c.region_id ? 1 : 0]);
out.edges = edges;

writeFileSync(
  join(here, "layout.js"),
  "// GENERATED by build-layout.mjs from docs/notes/*.json -- do not edit by hand.\nwindow.TSL = " + JSON.stringify(out) + ";\n",
);
console.log(`layout.js: ${out.countries.length} countries, ${edges.length} edges, ${Object.keys(out.cards).length} cards`);
