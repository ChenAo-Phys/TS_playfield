// Generates mc-data.js (inline data for the static mockup, works from file://).
// Run from the repo root:  node docs/design/mockup-mobile-clarity-assets/build-data.mjs
// Inputs: docs/notes/countries.json, docs/notes/cards_meta.json (both generated from DeepStruggle data).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const countries = JSON.parse(readFileSync(join(root, "docs/notes/countries.json"), "utf8"));
const cards = JSON.parse(readFileSync(join(root, "docs/notes/cards_meta.json"), "utf8"));

// Short labels used when a country box is drawn small. EN <= ~11 chars (condensed), ZH <= 4 glyphs.
const SHORT_EN = {
  "United Kingdom": "UK", "West Germany": "W. Germany", "East Germany": "E. Germany",
  Czechoslovakia: "Czechoslov.", "Spain/Portugal": "Spain/Port.", "West African States": "W. African St.",
  "Saharan States": "Saharan St.", "SE African States": "SE African St.", "Dominican Rep": "Dominican R.",
  "Laos/Cambodia": "Laos/Camb.", "North Korea": "N. Korea", "South Korea": "S. Korea",
  "South Africa": "S. Africa", "Saudi Arabia": "Saudi Arabia",
};
const SHORT_ZH = {
  6: "比荷卢", 16: "捷克", 9: "西葡", 49: "西非", 50: "撒哈拉", 61: "东南非", 73: "多米尼加",
  35: "老挝柬埔寨", 28: "沙特", 39: "印尼", 27: "海湾国家",
};
// Our glossary (map-i18n §3.6): multi-country boxes use the card-art forms.
const ZH_FIX = { 49: "西非国家", 50: "撒哈拉国家", 61: "东南非洲国家", 27: "海湾国家", 35: "老挝/柬埔寨" };

// Small nudges so 104x70 boxes never touch (reference board boxes are 95x63).
const NUDGE = { 21: [-3, 0], 22: [3, 0], 72: [-3, 0], 73: [3, 0], 6: [-2, 0], 7: [2, 0] };

const out = countries.map((c) => {
  const [dx, dy] = NUDGE[c.id] ?? [0, 0];
  const zh = ZH_FIX[c.id] ?? c.name_zh;
  return {
    id: c.id,
    en: c.name,
    enS: SHORT_EN[c.name] ?? c.short_name_en ?? c.name,
    zh,
    zhS: SHORT_ZH[c.id] ?? zh,
    x: c.ref_x + dx,
    y: c.ref_y + dy,
    st: c.stability,
    bg: c.battleground,
    r: c.region_id,
    we: c.subregions.includes("Western Europe"),
    ee: c.subregions.includes("Eastern Europe"),
    sea: c.subregions.includes("Southeast Asia"),
    sp: c.superpower_adjacent === "USA" ? "US" : c.superpower_adjacent, // normalise (critique 3.10)
    nb: c.neighbours,
  };
});

const cardOut = {};
for (const c of cards) {
  cardOut[c.id] = {
    ops: c.ops, side: c.side, era: c.era, sc: c.scoring, st: c.starred, war: c.war_card,
    en: c.title_en, zh: c.title_zh,
  };
}

const banner = "// GENERATED by build-data.mjs from docs/notes/{countries,cards_meta}.json. Do not edit.\n";
writeFileSync(
  join(here, "mc-data.js"),
  banner + "window.MC_COUNTRIES = " + JSON.stringify(out) + ";\nwindow.MC_CARDS = " + JSON.stringify(cardOut) + ";\n",
);
console.log("wrote", out.length, "countries,", Object.keys(cardOut).length, "cards");
